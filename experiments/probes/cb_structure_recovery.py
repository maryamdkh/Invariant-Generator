"""F' for CB2001: are the learned encoder rows the generalized invariants?

Fits the true J2^0 (quadratic) and J3^0 (cubic) of the generating CB2001
criterion onto the same 29 orthotropic monomials the encoder reads (least
squares, exact up to round-off), then compares with the learned raw rows:
cosine of each row with its invariant, and the relative coefficient error
after the best scale.

    uv run python experiments/probes/cb_structure_recovery.py <results-dir>/benchmark_summary.json \
        configs/cb/cb2001_2090T3.toml [--output json]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import torch

from invariant_generator.config import load_config
from invariant_generator.data import prepare_training_data
from invariant_generator.model import InvariantYieldModel
from invariant_generator.yield_criteria import CRITERIA

parser = argparse.ArgumentParser()
parser.add_argument("summary", type=Path)
parser.add_argument("config", type=Path)
parser.add_argument("--output", type=Path, default=None)
args = parser.parse_args()

config = load_config(args.config)
pipeline = json.loads(args.summary.read_text(encoding="utf-8"))[0]["pipeline"]
learned = np.asarray(pipeline["encoder_formulas"]["raw_coefficients"], dtype=float)
names = pipeline["encoder_formulas"]["invariant_names"]

data = prepare_training_data(config)
X = data.X_train
pool = InvariantYieldModel.from_config(config).double().invariant_pool
with torch.no_grad():
    F = pool(torch.as_tensor(X, dtype=torch.float64)).numpy()
meta = json.loads((Path(config.data.data_dir) / f"{config.data.dataset_name}.json").read_text())
criterion = CRITERIA[meta["criterion"]]
# The data were generated by applying the criterion to the stored columns
# directly (y matches criterion(X) to round-off), so no shear conversion.
J2, J3 = criterion.invariants(X)

result = {"monomials": names, "rows": []}
for target, label in ((J2, "J2^0"), (J3, "J3^0")):
    coeffs, *_ = np.linalg.lstsq(F, target, rcond=None)
    fit = np.linalg.norm(F @ coeffs - target) / np.linalg.norm(target)
    cosines = learned @ coeffs / (np.linalg.norm(learned, axis=1) * np.linalg.norm(coeffs))
    row = int(np.argmax(np.abs(cosines)))
    scale = learned[row] @ coeffs / (learned[row] @ learned[row])
    error = np.linalg.norm(scale * learned[row] - coeffs) / np.linalg.norm(coeffs)
    result["rows"].append({
        "invariant": label, "true_fit_residual": float(fit), "matched_row": f"J{row + 1}",
        "cosine": float(abs(cosines[row])), "relative_coefficient_error": float(error),
        "true_coefficients": coeffs.tolist(),
    })
    print(f"{label}: row J{row + 1}, cosine {abs(cosines[row]):.8f}, coefficient error {error:.2e}"
          f" (truth fit residual {fit:.1e})")
if args.output:
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
